#!/bin/bash
# Upgrade of an existing installation, from the unpacked installer.
#
#   ./upgrade.sh <installation directory>
#       loads the images shipped in this package, replaces that installation's
#       docker-compose.yml with this package's (the old one is kept next to it
#       as docker-compose.yml.<date>.bak), adds the configuration folders and
#       the .env setting this version needs without touching existing ones, and
#       restarts the stack there without contacting any registry.
#
#   ./upgrade.sh
#       only loads the images; you then update the installation's
#       docker-compose.yml yourself (this version adds the
#       openelis-analyzer-bridge service) and run `docker compose up -d` there.
set -euo pipefail
if [ $# -gt 0 ]; then
    target=$(cd "$1" && pwd)
fi
cd "$(dirname "$0")"

ensure_pairing_code() {
    local env_file=$1 code
    if grep -q '^ANALYZER_BRIDGE_PAIRING_CODE=..*' "${env_file}"; then
        return
    fi
    code=$(od -An -N16 -tx1 /dev/urandom | tr -d ' \n')
    if grep -q '^ANALYZER_BRIDGE_PAIRING_CODE=' "${env_file}"; then
        sed -i.bak "s/^ANALYZER_BRIDGE_PAIRING_CODE=.*/ANALYZER_BRIDGE_PAIRING_CODE=${code}/" "${env_file}"
        rm -f "${env_file}.bak"
    else
        printf '\n# Code OpenELIS pairs with the analyser Bridge on start; generated by the installer.\nANALYZER_BRIDGE_PAIRING_CODE=%s\n' "${code}" >> "${env_file}"
    fi
    echo "generated the analyser Bridge pairing code in ${env_file}"
}

if [ $# -gt 0 ]; then
    for required in docker-compose.yml .env configs; do
        if [ ! -e "${target}/${required}" ]; then
            echo "${target} is not an OpenELIS installation: ${required} is missing" >&2
            exit 1
        fi
    done
fi

echo "loading the images from dockerImage/openelis-images.tar.gz (this takes a few minutes)"
gunzip -c dockerImage/openelis-images.tar.gz | docker load

echo "loaded:"
cat dockerImage/images.txt

if [ $# -eq 0 ]; then
    echo "next: run ./upgrade.sh <installation directory>, or point the image tags in your existing"
    echo "docker-compose.yml at these images, add the openelis-analyzer-bridge service from this"
    echo "package's docker-compose.yml, and run: docker compose up -d"
    exit 0
fi

backup="${target}/docker-compose.yml.$(date +%Y%m%d%H%M%S).bak"
cp "${target}/docker-compose.yml" "${backup}"
cp docker-compose.yml "${target}/docker-compose.yml"
echo "replaced ${target}/docker-compose.yml; the previous one is ${backup}"

for entry in configs/*; do
    if [ ! -e "${target}/${entry}" ]; then
        cp -R "${entry}" "${target}/${entry}"
        echo "added ${entry}"
    fi
done
# The certs service runs this script; it changes with the package.
cp configs/certs/ensure-stores.sh "${target}/configs/certs/ensure-stores.sh"

ensure_pairing_code "${target}/.env"

cd "${target}"
if docker compose version >/dev/null 2>&1; then
    docker compose up -d --pull never
else
    docker-compose up -d
fi
echo "upgraded. If you had changed the previous docker-compose.yml, carry those changes over from ${backup}"
